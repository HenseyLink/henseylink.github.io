/***********************************
 * Internationalization
 ***********************************/
(function initI18n() {
    const html = document.documentElement;
    const toggles = document.querySelectorAll('.lang-toggle');

    function applyLanguage(lang, animate = false) {
        html.setAttribute('lang', lang);
        html.setAttribute('data-lang', lang);
        localStorage.setItem('lang', lang);

        function updateText() {
            document.querySelectorAll('[data-i18n]').forEach(el => {
                const key = el.getAttribute('data-i18n');
                if (translations[lang] && translations[lang][key]) {
                    if (el.tagName === 'META') {
                        el.setAttribute('content', translations[lang][key]);
                    } else {
                        el.textContent = translations[lang][key];
                    }
                }
            });

            document.querySelectorAll('[data-i18n-label]').forEach(el => {
                const key = el.getAttribute('data-i18n-label');
                if (translations[lang] && translations[lang][key]) {
                    el.setAttribute('data-label', translations[lang][key]);
                }
            });

            toggles.forEach(toggle => {
                const current = toggle.querySelector('.lang-current');
                if (current) {
                    current.textContent = lang.toUpperCase();
                }
                toggle.setAttribute('aria-label', translations[lang].lang_label);
            });

            document.querySelectorAll('.faq-item.is-open').forEach(item => {
                item.classList.remove('is-open');
                const answer = item.querySelector('.faq-answer');
                if (answer) {
                    gsap.set(answer, { maxHeight: 0, opacity: 0, y: -4 });
                }
            });

            window.setTimeout(() => {
                if (typeof ScrollTrigger !== 'undefined') {
                    ScrollTrigger.refresh();
                }
            }, 50);
        }

        if (animate && typeof gsap !== 'undefined') {
            gsap.to('.site-main', {
                opacity: 0.6,
                duration: 0.12,
                ease: 'power2.in',
                onComplete: () => {
                    updateText();
                    gsap.to('.site-main', {
                        opacity: 1,
                        duration: 0.2,
                        ease: 'power2.out'
                    });
                }
            });
        } else {
            updateText();
        }
    }

    const savedLang = localStorage.getItem('lang');
    const initialLang = savedLang || 'ru';
    applyLanguage(initialLang);

    toggles.forEach(toggle => {
        toggle.addEventListener('click', () => {
            const current = html.getAttribute('data-lang') || 'ru';
            const next = current === 'ru' ? 'en' : 'ru';
            applyLanguage(next, true);
        });
    });

    window.applyLanguage = applyLanguage;
})();


/***********************************
 * Theme toggle
 ***********************************/
(function initTheme() {
    const html = document.documentElement;
    const toggles = document.querySelectorAll('.theme-toggle');
    const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
    const savedTheme = localStorage.getItem('theme');
    const initialTheme = savedTheme || (prefersDark ? 'dark' : 'light');

    function applyTheme(theme, animate = false) {
        if (animate) {
            html.classList.add('theme-transition');
        }
        html.setAttribute('data-theme', theme);
        localStorage.setItem('theme', theme);

        if (typeof window.updateShaderTheme === 'function') {
            window.updateShaderTheme(theme === 'light' ? 1.0 : 0.0);
        }

        if (animate) {
            window.setTimeout(() => {
                html.classList.remove('theme-transition');
            }, 520);
        }
    }

    applyTheme(initialTheme, false);

    toggles.forEach(toggle => {
        toggle.addEventListener('click', () => {
            const current = html.getAttribute('data-theme') || 'dark';
            const next = current === 'dark' ? 'light' : 'dark';
            applyTheme(next, true);
        });
    });
})();


/***********************************
 * Lenis smooth scrolling
 ***********************************/
(function initLenis() {
    if (typeof Lenis === 'undefined') return;

    const lenis = new Lenis({
        duration: 1.2,
        easing: (t) => Math.min(1, 1.001 - Math.pow(2, -10 * t)),
        orientation: 'vertical',
        gestureOrientation: 'vertical',
        smoothWheel: true,
        touchMultiplier: 2
    });

    lenis.on('scroll', ScrollTrigger.update);

    gsap.ticker.add((time) => {
        lenis.raf(time * 1000);
    });

    gsap.ticker.lagSmoothing(0);

    window.lenis = lenis;

    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', (e) => {
            const href = anchor.getAttribute('href');
            if (!href || href === '#') return;
            const target = document.querySelector(href);
            if (!target) return;
            e.preventDefault();
            lenis.scrollTo(target, {
                offset: -90,
                duration: 1.4
            });
        });
    });
})();


/***********************************
 * Monochrome shader background
 ***********************************/
(function initMonochromeBackground() {
    const canvas = document.getElementById('bg-canvas');
    if (!canvas || typeof THREE === 'undefined') return;

    const scene = new THREE.Scene();
    const camera = new THREE.OrthographicCamera(-1, 1, 1, -1, 0, 1);

    const renderer = new THREE.WebGLRenderer({
        canvas,
        alpha: true,
        antialias: false
    });
    renderer.setSize(window.innerWidth, window.innerHeight);
    renderer.setPixelRatio(Math.min(window.devicePixelRatio, 1.5));

    const vertexShader = `
        varying vec2 vUv;
        void main() {
            vUv = uv;
            gl_Position = vec4(position, 1.0);
        }
    `;

    const fragmentShader = `
        precision mediump float;
        uniform float uTime;
        uniform float uTheme;
        varying vec2 vUv;

        float random(vec2 st) {
            return fract(sin(dot(st.xy, vec2(12.9898, 78.233))) * 43758.5453123);
        }

        float noise(vec2 p) {
            vec2 i = floor(p);
            vec2 f = fract(p);
            float a = random(i);
            float b = random(i + vec2(1.0, 0.0));
            float c = random(i + vec2(0.0, 1.0));
            float d = random(i + vec2(1.0, 1.0));
            vec2 u = f * f * (3.0 - 2.0 * f);
            return mix(a, b, u.x) + (c - a) * u.y * (1.0 - u.x) + (d - b) * u.x * u.y;
        }

        void main() {
            vec2 uv = vUv;
            float t = uTime * 0.04;

            float n = noise(uv * 3.0 + t * 0.3);
            n += noise(uv * 6.0 - t * 0.2) * 0.5;
            n += noise(uv * 12.0 + t * 0.1) * 0.25;
            n /= 1.75;

            vec3 darkBase = vec3(0.035);
            vec3 lightBase = vec3(0.94);
            vec3 base = mix(darkBase, lightBase, uTheme);
            vec3 noiseColor = mix(vec3(n * 0.025), vec3(-n * 0.015), uTheme);
            vec3 color = base + noiseColor;

            gl_FragColor = vec4(color, 1.0);
        }
    `;

    const uniforms = {
        uTime: { value: 0 },
        uTheme: { value: document.documentElement.getAttribute('data-theme') === 'light' ? 1.0 : 0.0 }
    };

    const material = new THREE.ShaderMaterial({
        vertexShader,
        fragmentShader,
        uniforms
    });

    const geometry = new THREE.PlaneGeometry(2, 2);
    const mesh = new THREE.Mesh(geometry, material);
    scene.add(mesh);

    let isVisible = true;
    document.addEventListener('visibilitychange', () => {
        isVisible = !document.hidden;
    });

    function animate() {
        requestAnimationFrame(animate);
        if (!isVisible) return;
        uniforms.uTime.value += 0.016;
        renderer.render(scene, camera);
    }
    animate();

    window.addEventListener('resize', () => {
        renderer.setSize(window.innerWidth, window.innerHeight);
    });

    window.updateShaderTheme = (value) => {
        gsap.to(uniforms.uTheme, {
            value: value,
            duration: 0.5,
            ease: 'power2.inOut'
        });
    };
})();


/***********************************
 * Scroll animations with GSAP
 ***********************************/
(function initScrollAnimations() {
    if (typeof gsap === 'undefined' || typeof ScrollTrigger === 'undefined') return;

    gsap.registerPlugin(ScrollTrigger);

    ScrollTrigger.config({
        ignoreMobileResize: true
    });

    function reveal(elements, fromVars, toVars, trigger, start = 'top 80%') {
        gsap.fromTo(elements,
            { opacity: 0, y: 30, ...fromVars },
            {
                opacity: 1,
                y: 0,
                duration: 0.8,
                ease: 'power2.out',
                scrollTrigger: {
                    trigger: trigger,
                    start: start,
                    once: true,
                    toggleActions: 'play none none none'
                },
                ...toVars
            }
        );
    }

    // Section headers
    document.querySelectorAll('.section-header').forEach(header => {
        reveal(header.children, {}, { duration: 0.8, stagger: 0.1 }, header, 'top 85%');
    });

    // Hero panel
    const heroPanel = document.querySelector('.panel--hero');
    if (heroPanel) {
        gsap.fromTo(heroPanel,
            { opacity: 0, y: 40, scale: 0.98 },
            { opacity: 1, y: 0, scale: 1, duration: 1, ease: 'power2.out' }
        );

        gsap.fromTo('.hero-badge', { opacity: 0, y: 20 }, { opacity: 1, y: 0, duration: 0.7, delay: 0.2, ease: 'power2.out' });
        gsap.fromTo('.hero-title', { opacity: 0, y: 30 }, { opacity: 1, y: 0, duration: 0.9, delay: 0.35, ease: 'power2.out' });
        gsap.fromTo('.hero-desc', { opacity: 0, y: 25 }, { opacity: 1, y: 0, duration: 0.8, delay: 0.5, ease: 'power2.out' });
        gsap.fromTo('.hero-actions .btn', { opacity: 0, y: 20 }, { opacity: 1, y: 0, duration: 0.6, stagger: 0.1, delay: 0.65, ease: 'power2.out' });
        gsap.fromTo('.platforms', { opacity: 0, y: 20 }, { opacity: 1, y: 0, duration: 0.7, delay: 0.85, ease: 'power2.out' });
    }

    // Regions
    const regionsPanel = document.querySelector('.panel--regions');
    const regionTags = document.querySelectorAll('.region-tag');
    const regionBanner = document.querySelector('.region-banner');
    if (regionBanner) {
        reveal(regionBanner, { y: 20 }, { duration: 0.7 }, regionBanner, 'top 88%');
    }
    if (regionsPanel) {
        reveal(regionsPanel, {}, { duration: 0.8 }, regionsPanel, 'top 80%');
        if (regionTags.length) {
            reveal(regionTags, { scale: 0.92 }, { duration: 0.55, stagger: 0.08, ease: 'back.out(1.4)' }, regionsPanel, 'top 75%');
        }
    }

    // Features
    const featureCards = document.querySelectorAll('.panel--feature');
    if (featureCards.length) {
        reveal(featureCards, {}, { duration: 0.7, stagger: 0.08 }, '.features-grid', 'top 80%');
        reveal('.feature-icon', { scale: 0.7 }, { duration: 0.5, stagger: 0.08, ease: 'back.out(1.4)' }, '.features-grid', 'top 78%');
    }

    // Pricing
    const pricingPanels = document.querySelectorAll('.panel--pricing');
    if (pricingPanels.length) {
        pricingPanels.forEach((panel) => {
            reveal(panel, { scale: 0.96 }, { duration: 0.9 }, panel, 'top 80%');
            const perks = panel.querySelectorAll('.pricing-perks li');
            if (perks.length) {
                reveal(perks, { x: -15 }, { duration: 0.5, stagger: 0.1 }, panel, 'top 70%');
            }
        });
    }

    // Payment methods
    const paymentMethods = document.querySelector('.payment-methods');
    if (paymentMethods) {
        reveal(paymentMethods, { y: 20 }, { duration: 0.7 }, paymentMethods, 'top 88%');
    }

    // FAQ
    const faqItems = document.querySelectorAll('.faq-item');
    if (faqItems.length) {
        reveal(faqItems, {}, { duration: 0.7, stagger: 0.12 }, '.faq-list', 'top 80%');
    }

    // Links / footer
    const linksPanel = document.querySelector('.panel--links');
    if (linksPanel) {
        reveal(linksPanel, {}, { duration: 0.8 }, linksPanel, 'top 85%');
    }

    const siteFooter = document.querySelector('.site-footer');
    if (siteFooter) {
        reveal(siteFooter, { y: 20 }, { duration: 0.8 }, siteFooter, 'top 95%');
    }

    window.addEventListener('load', () => {
        window.setTimeout(() => {
            ScrollTrigger.refresh();
        }, 100);
    });
})();


